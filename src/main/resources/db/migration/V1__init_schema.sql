CREATE TABLE users (
                       id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       email         VARCHAR(255) NOT NULL UNIQUE,
                       password_hash VARCHAR(100) NOT NULL,
                       name          VARCHAR(100) NOT NULL,
                       currency      VARCHAR(3)   NOT NULL DEFAULT 'BYN',
                       time_zone     VARCHAR(64)  NOT NULL DEFAULT 'Europe/Minsk',
                       role          VARCHAR(20)  NOT NULL DEFAULT 'USER',
                       enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
                       created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE families (
                          id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          name       VARCHAR(100) NOT NULL,
                          owner_id   BIGINT NOT NULL REFERENCES users (id),
                          created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE family_members (
                                id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                family_id BIGINT NOT NULL REFERENCES families (id) ON DELETE CASCADE,
                                user_id   BIGINT NOT NULL UNIQUE REFERENCES users (id) ON DELETE CASCADE,
                                role      VARCHAR(20) NOT NULL,
                                joined_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE family_invites (
                                id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                family_id  BIGINT NOT NULL REFERENCES families (id) ON DELETE CASCADE,
                                code       VARCHAR(16) NOT NULL UNIQUE,
                                created_by BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
                                expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
                                used_at    TIMESTAMP WITH TIME ZONE
);

CREATE TABLE accounts (
                          id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          user_id            BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
                          name               VARCHAR(100) NOT NULL,
                          type               VARCHAR(20)  NOT NULL,
                          currency           VARCHAR(3)   NOT NULL,
                          balance            NUMERIC(19, 2) NOT NULL DEFAULT 0,
                          shared_with_family BOOLEAN NOT NULL DEFAULT TRUE,
                          archived           BOOLEAN NOT NULL DEFAULT FALSE,
                          version            BIGINT  NOT NULL DEFAULT 0,
                          created_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE categories (
                            id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            user_id  BIGINT REFERENCES users (id) ON DELETE CASCADE,
                            name     VARCHAR(60) NOT NULL,
                            type     VARCHAR(20) NOT NULL,
                            archived BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE transactions (
                              id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              user_id           BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
                              account_id        BIGINT NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
                              target_account_id BIGINT REFERENCES accounts (id) ON DELETE CASCADE,
                              category_id       BIGINT REFERENCES categories (id),
                              type              VARCHAR(20) NOT NULL,
                              amount            NUMERIC(19, 2) NOT NULL CHECK (amount > 0),
                              title             VARCHAR(120) NOT NULL,
                              comment           VARCHAR(500),
                              operation_date    DATE NOT NULL,
                              created_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_tx_user_date ON transactions (user_id, operation_date);
CREATE INDEX idx_tx_account ON transactions (account_id);

CREATE TABLE budgets (
                         id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         user_id      BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
                         category_id  BIGINT NOT NULL REFERENCES categories (id) ON DELETE CASCADE,
                         month        DATE NOT NULL,
                         limit_amount NUMERIC(19, 2) NOT NULL CHECK (limit_amount > 0),
                         CONSTRAINT uq_budget UNIQUE (user_id, category_id, month)
);

CREATE TABLE goals (
                       id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       owner_id       BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
                       family_id      BIGINT REFERENCES families (id) ON DELETE SET NULL,
                       name           VARCHAR(100) NOT NULL,
                       target_amount  NUMERIC(19, 2) NOT NULL CHECK (target_amount > 0),
                       target_date    DATE NOT NULL,
                       inflation_rate NUMERIC(5, 2) NOT NULL DEFAULT 0,
                       annual_rate    NUMERIC(5, 2) NOT NULL DEFAULT 0,
                       created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE goal_contributions (
                                    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    goal_id        BIGINT NOT NULL REFERENCES goals (id) ON DELETE CASCADE,
                                    user_id        BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
                                    amount         NUMERIC(19, 2) NOT NULL CHECK (amount > 0),
                                    contributed_at DATE NOT NULL
);